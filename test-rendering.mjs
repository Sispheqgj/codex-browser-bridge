import assert from 'node:assert/strict';
import {JSDOM} from 'jsdom';
import {withProjects} from './projects.mjs';
const dom=new JSDOM('<!doctype html><body></body>',{url:'https://example.test/'});
globalThis.window=dom.window;globalThis.document=dom.window.document;
const {renderMarkdown}=await import('./markdown.mjs');
const block=document.createElement('div');
const example=(await import('node:fs')).readFileSync(new URL('./rendering-fixture.md',import.meta.url),'utf8');
renderMarkdown(block,example);
for(const selector of ['h2','strong','code','ol li','blockquote','.table-scroll table','pre code .hljs-keyword','.code-toolbar button','.katex','.katex-display','input[type="checkbox"][disabled]'])assert.ok(block.querySelector(selector),selector);
assert.equal(block.querySelectorAll('.katex').length,3);
assert.equal(block.querySelector('pre code').textContent,'def read_block(x):\n    return x + 1\n');
assert.equal(block.querySelector('a[href="https://example.test/doc"]').getAttribute('rel'),'noopener noreferrer');
assert.equal(block.querySelector('a[data-server-path]').getAttribute('href'),'#');
assert.equal(block.querySelector('img,script,iframe,[onerror],a[href^="javascript:"]'),null);
assert.ok(block.textContent.includes('<script>alert(1)</script>'));

const host='remote-ssh-discovered:test';
const state={'remote-projects':[{id:'a',hostId:host,label:'自定义名称',remotePath:'/work'},{id:'b',hostId:host,label:'子项目',remotePath:'/work/sub'},{id:'foreign',hostId:'remote-ssh-discovered:other',label:'另一台主机',remotePath:'/work'}],'project-order':['b','a'],'thread-project-assignments':{assigned:{projectKind:'remote',hostId:host,projectId:'a'},wrongHost:{projectKind:'remote',hostId:'other',projectId:'b'}}};
const input=[{id:'test',host:'test',threads:[{id:'assigned',cwd:'/elsewhere'},{id:'nested',cwd:'/work/sub/src'},{id:'sibling',cwd:'/work-other'},{id:'wrongHost',cwd:'/elsewhere'}]},{id:'other',host:'other',threads:[{id:'nested',cwd:'/work/sub'}]}];
const result=withProjects(input,state);
assert.deepEqual(result[0].projects.map(p=>p.id),['b','a']);
assert.deepEqual(result[0].threads.map(t=>t.projectId),['a','b',null,null]);
assert.equal(result[1].threads[0].projectId,'foreign');
assert.equal(result[0].threads.length,input[0].threads.length);
assert.equal(input[0].threads[0].projectId,undefined);
console.log('PASS: Markdown formatting, code, both math delimiters, sanitized links/HTML, and host-scoped project grouping');
